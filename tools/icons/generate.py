#!/usr/bin/env python3
"""Build only the five pinned Lucide icons, offline, as LVGL 8 alpha4 images."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ROOT / "third_party/icons/lucide"
SOURCE_COMMIT = "3fef7aca71a50acc54bd2f24f0cc4747c22aa6d2"
QT_VERSION = "6.12.0"
SUPERSAMPLE = 4
ICONS = (
    ("gauge", "ngk_icon_gauge_32", 32),
    ("activity", "ngk_icon_activity_32", 32),
    ("sliders-horizontal", "ngk_icon_sliders_32", 32),
    ("cpu", "ngk_icon_cpu_32", 32),
    ("triangle-exclamation-point", "ngk_icon_alert_20", 20),
)


def verify_sources() -> None:
    """Reject modified/missing inputs before rendering; never fetch from a network."""
    manifest = json.loads((SOURCES / "manifest.json").read_text())
    repository = "https://github.com/lucide-icons/lucide"
    if manifest["commit"] != SOURCE_COMMIT or manifest["repository"] != repository:
        raise ValueError("Lucide source commit/repository differs from the pinned input")
    expected = {"LICENSE", *(f"icons/{name}.svg" for name, _, _ in ICONS)}
    if set(manifest["files"]) != expected:
        raise ValueError("Unexpected Lucide input set")
    for name, entry in manifest["files"].items():
        expected_url = f"https://raw.githubusercontent.com/lucide-icons/lucide/{SOURCE_COMMIT}/{name}"
        if entry["url"] != expected_url:
            raise ValueError(f"Unexpected source URL for {name}")
        if hashlib.sha256((SOURCES / name).read_bytes()).hexdigest() != entry["sha256"]:
            raise ValueError(f"Lucide SHA-256 mismatch: {name}")


def require_qt() -> None:
    import PySide6
    from PySide6.QtCore import qVersion

    if PySide6.__version__ != QT_VERSION or qVersion() != QT_VERSION:
        raise RuntimeError(f"Use the local pinned PySide6/Qt {QT_VERSION} from requirements.lock")


def rasterize(name: str, size: int) -> bytes:
    """SVG alpha at 4x, integer box average; stroke/viewBox remain exactly upstream."""
    from PySide6.QtCore import QByteArray, QRectF
    from PySide6.QtGui import QImage, QPainter
    from PySide6.QtSvg import QSvgRenderer

    renderer = QSvgRenderer(QByteArray((SOURCES / f"icons/{name}.svg").read_bytes()))
    if not renderer.isValid():
        raise ValueError(f"Invalid SVG: {name}")
    side = size * SUPERSAMPLE
    image = QImage(side, side, QImage.Format.Format_ARGB32_Premultiplied)
    image.fill(0)
    painter = QPainter(image)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter, QRectF(0, 0, side, side))
    painter.end()
    count = SUPERSAMPLE * SUPERSAMPLE
    return bytes(
        (sum(image.pixelColor(x * SUPERSAMPLE + dx, y * SUPERSAMPLE + dy).alpha()
             for dy in range(SUPERSAMPLE) for dx in range(SUPERSAMPLE)) + count // 2) // count
        for y in range(size) for x in range(size)
    )


def pack_alpha4(alpha: bytes, width: int, height: int) -> bytes:
    """LVGL 8: rows byte aligned, x-even in high nibble, no palette/header in data."""
    if width <= 0 or height <= 0 or len(alpha) != width * height:
        raise ValueError("Alpha plane dimensions do not match")
    stride = (width + 1) // 2
    packed = bytearray(stride * height)
    for y in range(height):
        for x in range(width):
            value = (alpha[y * width + x] * 15 + 127) // 255
            packed[y * stride + x // 2] |= value << (4 if x % 2 == 0 else 0)
    return bytes(packed)


def generate() -> dict[Path, str]:
    verify_sources()
    require_qt()
    notice = (
        "/* Generated by tools/icons/generate.py; do not edit.\n"
        f" * Lucide {SOURCE_COMMIT}; ISC / retained MIT notices.\n"
        " * Copyright (c) 2026 Lucide Icons and Contributors.\n"
        " * See third_party/icons/lucide/LICENSE and README.md. */\n"
    )
    header = notice + '''#pragma once
#include "lvgl.h"

#ifdef __cplusplus
extern "C" {
#endif

enum { NGK_ICON_MENU_SIZE = 32, NGK_ICON_ALERT_SIZE = 20 };

/* Const alpha masks in flash. Set img_recolor for their theme color.
 * Create LVGL image widgets once; updating readings does not modify these assets. */
'''
    source = notice + '''#include "ui_icons.h"

#if LVGL_VERSION_MAJOR != 8
#error "These image descriptors target LVGL 8"
#endif

/* Alpha4: high nibble first; rows use (width + 1) / 2 bytes; no palette.
 * All pixel planes and descriptors are const; there is no runtime conversion. */
'''
    total = 0
    for name, symbol, size in ICONS:
        packed = pack_alpha4(rasterize(name, size), size, size)
        total += len(packed)
        header += f"extern const lv_img_dsc_t {symbol};\n"
        source += f"\nstatic const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {symbol}_map[] = {{\n"
        for start in range(0, len(packed), 16):
            source += "    " + ", ".join(f"0x{value:02x}" for value in packed[start:start + 16]) + ",\n"
        source += "};\n\n"
        source += f"const lv_img_dsc_t {symbol} = {{\n"
        source += f"    .header = {{ .cf = LV_IMG_CF_ALPHA_4BIT, .always_zero = 0, .reserved = 0, .w = {size}, .h = {size} }},\n"
        source += f"    .data_size = sizeof({symbol}_map),\n"
        source += f"    .data = {symbol}_map,\n}};\n"
    header += "\n#ifdef __cplusplus\n}\n#endif\n"
    source += f"\n/* Total alpha payload: {total} bytes; descriptors are additional. */\n"
    return {
        ROOT / "firmware/ecu/include/ui_icons.h": header,
        ROOT / "firmware/ecu/src/ui_icons.c": source,
    }


def preview(destination: Path) -> None:
    """Native pixels on the first row, nearest-neighbor 3x view below, no font use."""
    from PySide6.QtCore import Qt
    from PySide6.QtGui import QColor, QImage, QPainter

    sheet = QImage(5 * 112, 156, QImage.Format.Format_ARGB32)
    sheet.fill(QColor("#080808"))
    painter = QPainter(sheet)
    for index, (name, _, size) in enumerate(ICONS):
        alpha = pack_alpha4(rasterize(name, size), size, size)
        icon = QImage(size, size, QImage.Format.Format_ARGB32)
        for y in range(size):
            for x in range(size):
                value = (alpha[y * ((size + 1) // 2) + x // 2] >> (4 if x % 2 == 0 else 0)) & 15
                icon.setPixelColor(x, y, QColor(255, 152, 36, value * 17))
        painter.drawImage(index * 112 + (112 - size) // 2, 8, icon)
        zoom = icon.scaled(size * 3, size * 3, Qt.AspectRatioMode.KeepAspectRatio,
                           Qt.TransformationMode.FastTransformation)
        painter.drawImage(index * 112 + (112 - zoom.width()) // 2, 52, zoom)
    painter.end()
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not sheet.save(str(destination)):
        raise RuntimeError(f"Cannot save preview: {destination}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in outputs without writing")
    parser.add_argument("--preview", type=Path, help="Optional local PNG contact sheet")
    args = parser.parse_args()
    outputs = generate()
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise RuntimeError(f"Generated icon output differs: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
    if args.preview:
        preview(args.preview)
    print("Icons match pinned sources: 4 x 32x32 + 1 x 20x20, alpha4, 2248 pixel bytes")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, RuntimeError, ImportError) as error:
        print(f"Icon generation failed: {error}", file=sys.stderr)
        sys.exit(1)
